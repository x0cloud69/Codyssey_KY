-- =====================================================================
-- data.sql : 샘플 데이터 (schema.sql 실행 후 실행)
--
-- [입력 순서]
--   FK 가 참조하는 부모 테이블에 데이터가 먼저 있어야 자식 행을 넣을 수 있다.
--   예) orders 에 customer_id = 3 인 주문을 넣으려면 customer 에 id = 3 인 고객이 먼저 있어야 한다.
--   그래서 아래 순서로 입력한다.
--     category -> customer  (아무것도 참조하지 않는 부모)
--     menu                  (category 참조)
--     orders                (customer 참조)
--     order_item            (orders, menu 참조)
--
-- [id 를 직접 지정한 이유]
--   INTEGER PRIMARY KEY 는 생략하면 자동으로 번호가 붙지만, 자식 테이블에서 FK 로
--   어느 행을 가리키는지 한눈에 보이도록 모든 id 를 직접 적었다.
--
-- [INSERT 문법]
--   INSERT INTO 테이블 (컬럼1, 컬럼2, ...) VALUES (값1, 값2, ...), (값1, 값2, ...), ...;
--   VALUES 뒤에 괄호를 쉼표로 이어 쓰면 한 문장으로 여러 행을 넣을 수 있다.
--   컬럼 목록을 적어 두면 테이블 컬럼 순서가 바뀌어도 값이 엉뚱한 컬럼에 들어가지 않는다.
--
-- [쿼리 확인용으로 일부러 넣은 데이터]
--   customer 11, 12번 : 주문 이력 없음        -> LEFT JOIN(Q08 과 같은 유형) / NOT IN 서브쿼리(Q13) 확인용
--   menu 19번         : 판매 종료(is_available = 0) -> WHERE 조건(Q01) 확인용
--   menu 20번         : 판매 이력 없는 신메뉴 -> LEFT JOIN + IS NULL(Q08) 확인용
--   orders 4, 12번    : 취소(CANCELED) 주문   -> 집계 제외 조건, DELETE + CASCADE(Q17) 확인용
--   orders 19, 20번   : 접수(ORDERED) 상태    -> 처리 대기 주문 조회(Q07) 확인용
-- =====================================================================

